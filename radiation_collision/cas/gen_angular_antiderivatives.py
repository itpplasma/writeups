"""Find antiderivatives for the angular integrals of the diffusion tensor.

SymPy only proposes candidates. They are written to
angular_antiderivatives.wl and verified by fortsym in angular_integrals.wl,
by differentiation and exact endpoint evaluation.

Variables: g = gamma, ua = u_par, eta = cos(theta); u^2 = g^2 - 1 and
u_perp^2 = g^2 - 1 - ua^2, so every quantity is polynomial in (g, ua, eta)
apart from powers of Q.
"""
import sympy as sp

eta, g, ua = sp.symbols('eta g ua')
u2 = g**2 - 1
p2 = u2 - ua**2
sigma = 1 - eta**2
q = g - eta*ua
Q = sp.expand(u2*eta**2 - 2*g*ua*eta + 1 + ua**2)
assert sp.expand(Q - (q**2 - p2*sigma)) == 0

P5 = sp.expand(4*q**2 + 3*p2*sigma)                    # over Q^(5/2)
P7 = sp.expand((g*eta - ua)**2*(4*q**2 + p2*sigma))    # over Q^(7/2)


def antiderivative(P, k):
    """R/Q^((k-2)/2) + c*L with L' = Q^(-1/2), whose derivative is P/Q^(k/2)."""
    deg = max(sp.Poly(P, eta).degree(), k)
    cs = sp.symbols(f'c0:{deg+1}')
    R = sum(cs[j]*eta**j for j in range(deg))
    c = cs[deg]
    lhs = sp.expand(sp.diff(R, eta)*Q - sp.Rational(k - 2, 2)*R*sp.diff(Q, eta)
                    + c*Q**((k - 1)//2))
    sol = sp.solve(sp.Poly(lhs - P, eta).all_coeffs(), cs, dict=True)[0]
    # A free coefficient multiplies Q^((k-2)/2) in R: a constant of
    # integration.
    free = {x: 0 for x in cs if x not in sol}
    return (sp.factor(R.subs(sol).subs(free)),
            sp.factor(c.subs(sol).subs(free)))


def split(R, c):
    """R = Rn/Dn and c = Cn/Dn over one polynomial denominator Dn."""
    Dn = sp.lcm(sp.denom(sp.together(R)), sp.denom(sp.together(c)))
    return (sp.expand(sp.cancel(R*Dn)), sp.expand(sp.cancel(c*Dn)),
            sp.factor(Dn))


if __name__ == '__main__':
    code = sp.printing.mathematica.mathematica_code
    with open('angular_antiderivatives.wl', 'w') as out:
        out.write('(* Generated by gen_angular_antiderivatives.py: for the '
                  'integrand eta^j P/Q^(k/2),\n   Phi = (Rn/Q^((k-2)/2) + '
                  'Cn*L)/Dn with dL/deta = Q^(-1/2).\n   Verified in '
                  'angular_integrals.wl. *)\n')
        for j in range(3):
            for P, k, tag in ((P5, 5, 'a'), (P7, 7, 'b')):
                R, c = antiderivative(sp.expand(P*eta**j), k)
                Rn, Cn, Dn = split(R, c)
                out.write(f'R{tag}{j} = {code(Rn)};\n')
                out.write(f'C{tag}{j} = {code(Cn)};\n')
                out.write(f'D{tag}{j} = {code(Dn)};\n')
