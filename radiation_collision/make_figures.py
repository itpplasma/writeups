# --------------------------------------------------- absorption normalisation --
def S_M(s, eta, mu, pol, kmax=40):
    sig = 1 - eta**2
    tot = 0.0
    for k in range(1, kmax + 1):
        if (k*s)**2 <= sig:
            continue
        h = np.sqrt((k*s)**2 - sig)
        a, b = mu*eta*h/sig, h/s
        if pol == "O":
            f = lambda x: np.exp(-a*x)*x**2*special.jv(k, b*np.sqrt(1 - x**2))**2
        else:
            f = lambda x: np.exp(-a*x)*(1 - x**2)*special.jvp(k, b*np.sqrt(1 - x**2))**2
        term = h**3/sig**2*np.exp(-mu*k*s/sig)*integrate.quad(f, -1, 1, limit=200)[0]
        tot += term
        if term < 1e-14*tot:
            break
    return tot


