# ---------------------------------------------------- harmonic convergence --
def Dgg_partial(up, ua, nmax):
    """Partial harmonic sums of D^{gg}/nu0 from Eq. (3.2), n = 1..nmax."""
    g = np.sqrt(1 + up**2 + ua**2)
    n = np.arange(1, nmax + 1)

    def terms(eta):
        q = g - eta*ua
        sig = 1 - eta**2
        lam = n*up*np.sqrt(sig)/q
        dx = up**2/g**2*special.jvp(n, lam)**2
        do = (g*eta - ua)**2/(g**2*sig)*special.jv(n, lam)**2 if sig > 0 else 0*n
        return g/q**3*n**2*(dx + do)
    # Gauss-Legendre in eta: the integrand is smooth on [-1, 1] (q > 0).
    eta, w = np.polynomial.legendre.leggauss(400)
    vals = np.array([terms(e) for e in eta])
    return np.cumsum((vals*w[:, None]).sum(0))


