# ---------------------------------------------------------------- F, G, H --
def F_direct(u):
    g = np.sqrt(1 + u**2)
    return 10 + 3/u**2 - (9/(g*u) + 3*g/u**3)*np.arcsinh(u)


def G_direct(u):
    g = np.sqrt(1 + u**2)
    return 10 + 15/u**2 - (21/(g*u) + 15*g/u**3)*np.arcsinh(u)


def F_series(u):
    return 32/5*u**2 - 176/35*u**4 + 64/15*u**6 - 4352/1155*u**8


def H_series(u):
    return 27/35*u**4 - 68/105*u**6 + 656/1155*u**8


def FH(u):
    """F and H with the origin series below u = 0.1 (truncation < 1e-9 rel)."""
    u = np.asarray(u, float)
    small = u < 0.1
    us = np.where(small, 0.5, u)
    F = np.where(small, F_series(u), F_direct(us))
    H = np.where(small, H_series(u), us**2 - 1 - G_direct(us)/16)
    return F, H


def D_closed(up, ua):
    """Closed tensor in units of a = 2 nu0/3: (D^gg, D^ga, D^aa)/a."""
    u = np.sqrt(up**2 + ua**2)
    g = np.sqrt(1 + u**2)
    F, H = FH(u)
    return up**2, ua*up**2/g, up**2/u**2*(F/16 + H*ua**2/u**2)


